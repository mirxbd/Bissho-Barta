/**
 * Resolves a complete, realistic PublicUserProfile for any user name/avatar.
 * Integrates live friends list to accurately display friendship status.
 */
export function getPublicProfile(
  name: string,
  avatar?: string,
  friends: Friend[] = [],
  currentUserProfile?: UserProfile
): PublicUserProfile {
  // If viewing current user's profile
  if (currentUserProfile && (name === currentUserProfile.name || (avatar && avatar === currentUserProfile.avatar))) {
    return {
      name: currentUserProfile.name,
      avatar: currentUserProfile.avatar,
      coverPhoto: currentUserProfile.coverPhoto || 'https://images.unsplash.com/photo-1507525428034-b723cf961d3e?auto=format&fit=crop&w=1200&h=450&q=80',
      bio: currentUserProfile.bio || 'Simplicity is the ultimate sophistication. Building fast web applications.',
      location: currentUserProfile.location || 'San Francisco, CA',
      work: currentUserProfile.work || 'Software Engineer at TechCorp',
      education: currentUserProfile.education || 'Stanford University',
      relationship: currentUserProfile.relationship || 'In a relationship',
      mutualFriends: 0,
      friendsCount: friends.filter(f => f.status === 'friend').length,
      followersCount: currentUserProfile.followersCount || 1250,
      followingCount: currentUserProfile.followingCount || 184,
      joinedDate: 'Joined Bissho Barta in 2023',
      isOnline: true,
      status: 'friend',
      verified: true,
      badge: 'Account Owner',
      email: 'mirxbd@gmail.com',
      photos: [
        'https://images.unsplash.com/photo-1507525428034-b723cf961d3e?auto=format&fit=crop&w=600&h=600&q=80',
        'https://images.unsplash.com/photo-1518770660439-4636190af475?auto=format&fit=crop&w=600&h=600&q=80',
        'https://images.unsplash.com/photo-1550745165-9bc0b252726f?auto=format&fit=crop&w=600&h=600&q=80',
      ]
    };
  }

  // Check known public profiles
  const known = knownPublicProfiles[name];
  
  // Find in user's friends list
  const matchedFriend = friends.find(
    f => f.name.toLowerCase() === name.toLowerCase() || (avatar && f.avatar === avatar)
  );

  const effectiveAvatar = avatar || known?.avatar || matchedFriend?.avatar || 'https://images.unsplash.com/photo-1535713875002-d1d0cf377fde?auto=format&fit=crop&w=300&h=300&q=80';
  const effectiveCover = known?.coverPhoto || 'https://images.unsplash.com/photo-1507525428034-b723cf961d3e?auto=format&fit=crop&w=1200&h=450&q=80';

  // Determine friendship status
  const effectiveStatus = matchedFriend ? matchedFriend.status : (known?.status || 'none');
  const isOnline = matchedFriend ? (matchedFriend.isOnline ?? false) : (known?.isOnline ?? false);
  const mutualFriends = matchedFriend ? matchedFriend.mutualFriends : (known?.mutualFriends ?? Math.floor((name.length * 3) % 15) + 1);

  if (known) {
    return {
      id: matchedFriend?.id || known.id || `user-${name.toLowerCase().replace(/\s+/g, '-')}`,
      name: known.name || name,
      avatar: effectiveAvatar,
      coverPhoto: effectiveCover,
      bio: known.bio || `Welcome to ${name}'s official profile on Bissho Barta! Stay connected for news, posts, and daily updates.`,
      location: known.location || 'Dhaka, Bangladesh',
      work: known.work || 'Creative Professional & Creator',
      education: known.education || 'University of Dhaka',
      relationship: known.relationship || 'Single',
      mutualFriends: mutualFriends,
      friendsCount: known.friendsCount || 420,
      followersCount: known.followersCount || 1540,
      followingCount: known.followingCount || 280,
      joinedDate: known.joinedDate || 'Member since 2022',
      isOnline: isOnline,
      status: effectiveStatus,
      verified: known.verified ?? false,
      badge: known.badge,
      photos: known.photos || [
        effectiveCover,
        effectiveAvatar,
        'https://images.unsplash.com/photo-1506744038136-46273834b3fb?auto=format&fit=crop&w=600&h=600&q=80',
      ],
      website: known.website,
    };
  }

  // Fallback for any other user (commenters, other video authors, etc.)
  return {
    id: matchedFriend?.id || `user-${name.toLowerCase().replace(/\s+/g, '-')}`,
    name: name,
    avatar: effectiveAvatar,
    coverPhoto: effectiveCover,
    bio: `Active member of the Bissho Barta social community. Sharing thoughts, connecting with friends, and discovering world stories. 🌟`,
    location: 'Dhaka, Bangladesh',
    work: 'Digital Creator & Contributor',
    education: 'Dhaka University',
    relationship: 'Public Profile',
    mutualFriends: mutualFriends,
    friendsCount: 380,
    followersCount: 1120,
    followingCount: 340,
    joinedDate: 'Joined Bissho Barta 2023',
    isOnline: isOnline,
    status: effectiveStatus,
    verified: false,
    photos: [
      effectiveCover,
      effectiveAvatar,
      'https://images.unsplash.com/photo-1507525428034-b723cf961d3e?auto=format&fit=crop&w=600&h=600&q=80',
    ],
  };
}
